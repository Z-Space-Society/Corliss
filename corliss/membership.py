# --- The registry as an OAuth party ----------------------------------------
#
# To *write* to the registry an admin needs a HappyView session, and getting one
# has a constraint that decides the shape of Corliss's whole login path:
#
# **HappyView provisions the DPoP key itself.** `POST /oauth/dpop-keys` returns
# a private JWK, and a client is expected to run its atproto handshake with that
# key before handing the resulting tokens back at `POST /oauth/sessions`.
# HappyView holds the key so it can prove possession to the PDS on the member's
# behalf.
#
# The consequence: **Corliss cannot register a session from tokens it already
# has.** An ordinary login binds its tokens to the ephemeral key
# `atproto.generate_key()` mints per flow, which HappyView has never seen and
# cannot use. Whoever does the handshake has to already be using HappyView's
# key — which is why `views.login` asks the roster *before* PAR and provisions
# from here when the answer is yes. See that function for why deciding on an
# unverified DID is safe.
#
# Corliss is a **public** client here, exactly as the SPA is: a client key and
# a PKCE verifier binding the provision to the registration, no client secret.
# Nothing needs one — the pair is single-use and short-lived — and not minting
# a secret keeps this repo's answer to "what can this key do if it leaks" the
# same as scn-member-registry's: register a session for someone who has already
# authorised, which still cannot write anything the roster does not allow.


def provision_registry_key(registry, *, pkce_challenge):
    """Ask HappyView for a DPoP keypair. Returns `(provision_id, private_key)`.

    The key comes back as a private JWK and leaves here as a `cryptography` EC
    key, so callers hold the same type `atproto.generate_key()` returns and
    nothing downstream needs to know where it came from.

    Raises `RegistryError`. Callers on the login path must treat that as
    "no approve powers this session", never as a failed login: HappyView being
    unreachable means no approvals, which is a documented consequence, and must
    not escalate into nobody being able to sign in.
    """
    if not registry.url or not registry.client_key:
        raise RegistryError(
            "registry is not configured for sessions: MEMBERSHIP_REGISTRY_URL "
            "and MEMBERSHIP_REGISTRY_CLIENT_KEY must both be set"
        )
    payload = registry._post(
        "/oauth/dpop-keys", {"pkce_challenge": pkce_challenge}
    )
    provision_id = payload.get("provision_id")
    jwk = payload.get("dpop_key")
    if not provision_id or not isinstance(jwk, dict):
        raise RegistryError("registry did not return a DPoP key provision")
    try:
        # PyJWT is already a dependency and already parses JWKs for the OIDC
        # half; no second key library for one conversion.
        key = ECAlgorithm.from_jwk(json.dumps(jwk))
    except (ValueError, TypeError, InvalidKeyError) as exc:
        raise RegistryError(f"registry returned an unusable DPoP key: {exc}") from exc
    if not isinstance(key, ec.EllipticCurvePrivateKey):
        # A public key would leave the session unable to sign anything, and the
        # failure would surface much later as an unexplained 401.
        raise RegistryError("registry returned a public DPoP key, not a private one")
    return provision_id, key


def register_registry_session(
    registry,
    *,
    provision_id,
    pkce_verifier,
    did,
    token_data,
    pds_url,
    issuer,
    scopes,
):
    """Hand the freshly-exchanged tokens to HappyView as a session for `did`.

    After this the admin can call procedures: HappyView resolves the bearer to
    `did`, the Lua reads that as `caller_did`, and the runtime stamps it as the
    author of whatever gets written.

    Raises `RegistryError`, which on the login path is not fatal — see
    `provision_registry_key`.
    """
    payload = {
        "provision_id": provision_id,
        "pkce_verifier": pkce_verifier,
        "did": did,
        "access_token": token_data.get("access_token", ""),
        "refresh_token": token_data.get("refresh_token", ""),
        "scopes": scopes,
        "pds_url": pds_url,
        "issuer": issuer,
    }
    result = registry._post("/oauth/sessions", payload)
    if result.get("did") != did:
        raise RegistryError(
            f"registry registered a session for {result.get('did')!r}, not {did!r}"
        )
    return result


class MembershipRegistry:
    """The SCN registry, as a thing Corliss reads membership out of.

        registry = MembershipRegistry.from_settings()
        report = registry.reconcile(dry_run=True)

    Constructed with its configuration rather than reaching for `settings`
    inside every method, so a test can point it anywhere and never touch the
    network.
    """

    __slots__ = ("url", "client_key", "token", "host")

    def __init__(self, url, client_key, token, host=""):
        self.url = (url or "").rstrip("/")
        self.client_key = client_key or ""
        self.token = token or ""
        # The Host header to present, when it differs from the URL's authority.
        # See `fetch_events` — this is what makes the internal address usable.
        self.host = host or ""

    @classmethod
    def from_settings(cls):
        return cls(
            settings.MEMBERSHIP_REGISTRY_URL,
            settings.MEMBERSHIP_REGISTRY_CLIENT_KEY,
            settings.MEMBERSHIP_REGISTRY_TOKEN,
            settings.MEMBERSHIP_REGISTRY_HOST,
        )

    @property
    def is_configured(self):
        """The url and the token. Asked before offering to run, so an
        unconfigured deployment shows a reason rather than a traceback.

        The client key is deliberately **not** required. Verified against
        production 2026-08-18: HappyView dispatches to a Lua script with no
        session and no client key at all — a bare XRPC call reaches `handle()`
        and gets the script's own error back. So the key adds nothing the token
        does not already carry here.

        That is not a micro-optimisation. The key is the *console's*
        origin-bound key, and requiring it would mean a cluster rebuilt before
        `zai-set-console client_key` had been run could not reconcile — tying
        the recovery path to the console being configured, when the whole point
        of this path is that it works when nothing else does.
        """
        return bool(self.url and self.token)

    def _query(self, nsid, params=None):
        """Call one XRPC *query* on the registry and return its JSON object.

        Every read Corliss makes of HappyView goes through here, so the two
        things that make reaching it at an internal address work — the `Host`
        header and the client key — are written once rather than per caller.
        """
        # Sent when we have one, omitted when we don't — see `is_configured`.
        # Harmless either way, and not something the call depends on.
        headers = {"x-client-key": self.client_key} if self.client_key else {}

        # The registry routes by virtual host, so reaching it at its internal
        # address needs the public name presented explicitly: a request whose
        # Host is a bare `10.1.1.x:3000` is refused with HTTP 421 "Unknown host"
        # before any routing happens. The edge normally supplies this — Caddy
        # preserves the original Host when it proxies — which is exactly why the
        # bypass has to do it by hand. Blank means "use the URL's own authority",
        # which is what a deployment pointed at the public origin wants.
        if self.host:
            headers["Host"] = self.host

        try:
            response = requests.get(
                f"{self.url}/xrpc/{nsid}",
                params=params or {},
                headers=headers,
                timeout=REGISTRY_TIMEOUT,
            )
        except requests.RequestException as exc:
            raise RegistryError(f"could not reach the registry: {exc}") from exc

        if response.status_code != 200:
            # The body carries the Lua's own error message ("forbidden: invalid
            # service token" and friends), which is the half an operator needs.
            raise RegistryError(
                f"registry returned HTTP {response.status_code}: "
                f"{response.text[:300]}"
            )

        try:
            payload = response.json()
        except ValueError as exc:
            raise RegistryError("registry response was not JSON") from exc
        if not isinstance(payload, dict):
            raise RegistryError("registry response was not a JSON object")
        return payload

    def _post(self, path, payload):
        """POST JSON to one of the registry's own (non-XRPC) endpoints.

        Its OAuth surface — `/oauth/dpop-keys`, `/oauth/sessions` — rather than
        `/xrpc/...`. Unauthenticated in the DPoP sense: there is no session yet,
        which is what these calls exist to create. The client key is what
        identifies the caller, and it is required here even though `_query` does
        without one.
        """
        try:
            response = requests.post(
                f"{self.url}{path}",
                json=payload,
                headers={"Content-Type": "application/json", **self._headers()},
                timeout=REGISTRY_TIMEOUT,
            )
        except requests.RequestException as exc:
            raise RegistryError(f"could not reach the registry: {exc}") from exc

        if not response.ok:
            raise RegistryError(
                f"registry returned HTTP {response.status_code} for {path}: "
                f"{response.text[:300]}"
            )
        try:
            body = response.json()
        except ValueError as exc:
            raise RegistryError(f"registry response to {path} was not JSON") from exc
        if not isinstance(body, dict):
            raise RegistryError(f"registry response to {path} was not an object")
        return body

    def public_url(self, path):
        """The URL the registry believes it is serving, for `path`.

        **Not where the request goes** — that is `self.url`, the internal
        address. This is the name a DPoP proof has to claim, and the two differ
        for exactly the reason `MEMBERSHIP_REGISTRY_HOST` exists at all: the
        registry routes by virtual host, so Corliss dials a private address and
        presents the public name, and the registry then reconstructs the request
        URI from that header. A proof signed for the address we dialled is
        refused with `DPoP proof htu mismatch` — the same internal-address-with-
        a-public-name trap that HTTP 421 was, one layer up.

        HTTPS unless the host says otherwise, because the public origin is
        behind the edge's TLS and that is the origin the registry knows itself
        by — the SPA reaches it there and its proofs are accepted. A deployment
        whose registry is genuinely plain HTTP can say so by putting the scheme
        in the host value.
        """
        if not self.host:
            return f"{self.url}{path}"
        origin = self.host if "://" in self.host else f"https://{self.host}"
        return f"{origin.rstrip('/')}{path}"

    def _headers(self):
        """The two headers every call to the registry carries.

        `Host` is what makes the internal address usable at all — see `_query`.
        The client key identifies which registry client is calling; a query does
        not need it, and a procedure does.
        """
        headers = {}
        if self.client_key:
            headers["x-client-key"] = self.client_key
        if self.host:
            headers["Host"] = self.host
        return headers

    def _procedure(self, nsid, payload, *, token):
        """Call one XRPC *procedure* on the registry, as the admin who owns
        `token`. Returns its JSON object.

        The authenticated sibling of `_query`, and the asymmetry between them is
        the whole architecture in miniature. A query dispatches with no session
        at all, which is why every read script begins by checking `caller_did`
        itself. A procedure never reaches the script without DPoP
        authentication — HappyView refuses it with "XRPC procedures require
        DPoP authentication" first — and that refusal is exactly what makes a
        write safe to expose: no shared token can produce a proof, so no shared
        token can ever author a grant.

        What authenticates here is the **admin's own** session: their access
        token as the bearer, and a proof signed by the DPoP key HappyView
        provisioned for them at login. `caller_did` follows from that, the Lua
        checks it against the roster, and the runtime stamps it as the record's
        author. There is deliberately no way to call this as Corliss itself.
        """
        if not self.url:
            raise RegistryError(
                "registry is not configured: MEMBERSHIP_REGISTRY_URL must be set"
            )
        if not self.client_key:
            # Unlike a query, which works without one. Said plainly because the
            # fix is a deployment step (`zai-set-console client_key`), not a bug.
            raise RegistryError(
                "registry is not configured for writes: "
                "MEMBERSHIP_REGISTRY_CLIENT_KEY must be set"
            )

        dpop_key = atproto.key_from_pem(token.dpop_private_pem)
        try:
            response, nonce = atproto.post_json_with_dpop(
                f"{self.url}/xrpc/{nsid}",
                payload,
                token.access_token,
                dpop_key,
                nonce=token.dpop_nonce or None,
                headers=self._headers(),
                # Signed for the public name, sent to the private address.
                htu=self.public_url(f"/xrpc/{nsid}"),
                timeout=REGISTRY_TIMEOUT,
            )
        except requests.RequestException as exc:
            raise RegistryError(f"could not reach the registry: {exc}") from exc

        if nonce and nonce != token.dpop_nonce:
            token.dpop_nonce = nonce
            token.save(update_fields=["dpop_nonce", "updated_at"])

        if response.status_code != 200:
            # A Lua `error()` comes back as HTTP 500 with the script's own text
            # ("forbidden: caller is not a current admin"), which is the half an
            # operator — or an admin who has just been removed from the roster —
            # actually needs to read.
            raise RegistryError(
                f"registry returned HTTP {response.status_code}: "
                f"{response.text[:300]}"
            )

        try:
            payload = response.json()
        except ValueError as exc:
            raise RegistryError("registry response was not JSON") from exc
        if not isinstance(payload, dict):
            raise RegistryError("registry response was not a JSON object")
        return payload

    def approve(self, token, did, tier):
        """Grant membership at `tier`, authored by the admin behind `token`.

        **Also how a tier change is made.** Re-approving writes a fresh grant
        and latest-event-wins resolves it; no record is ever edited, and the old
        grant stays in the space as the history of what was decided when. So
        there is no `change_tier` here and there should not be one — it would be
        a second name for this call and would imply an edit that never happens.

        Approving twice is harmless for the same reason, which matters because
        the push that clears the row from the queue is asynchronous and an admin
        may well click again before it lands.
        """
        if tier not in TIERS:
            # Refused here as well as in the Lua. A tierless or unknown grant is
            # a fail-open bug rather than a harmless default — a consumer that
            # turns it into an empty group claim makes Open WebUI remove
            # nothing, so the member silently keeps the tier they had.
            raise RegistryError(f"not a tier this network issues: {tier!r}")
        return self._procedure(
            APPROVE_MEMBER_NSID, {"did": did, "tier": tier}, token=token
        )

    def revoke(self, token, did, reason=""):
        """End membership, authored by the admin behind `token`.

        A revocation is a **new record**, never a deletion: the space is
        append-only, so what this writes is the event "access ended here", and
        the grant it answers stays exactly where it was. A member is active iff
        there is a grant with no later revocation.
        """
        payload = {"did": did}
        reason = (reason or "").strip()
        if reason:
            payload["reason"] = reason[:REASON_MAX_CHARS]
        return self._procedure(REVOKE_MEMBER_NSID, payload, token=token)

    def set_space_access(self, token, did, access):
        """Grant or remove registry space write access for an admin.

        Space membership is what makes a grant authoritative — an admin without
        it is on the roster and still cannot approve anyone — so this is the
        second half of a roster edit, not an optional extra.

        **`token` must be the service account's.** The space runtime accepts
        member changes only from the space authority, which is the service DID;
        an ordinary admin's session is refused however current they are. That is
        the reverse of `approve`/`revoke`, where the acting admin's own session
        is exactly what must be used, and the asymmetry is the registry's, not
        a choice made here.

        Idempotent both ways in the Lua, so retrying a partial roster edit is
        safe and is the documented recovery.
        """
        if access not in ("write", "none"):
            raise RegistryError(f"not a space access level: {access!r}")
        return self._procedure(
            SET_SPACE_ACCESS_NSID, {"did": did, "access": access}, token=token
        )

    def fetch_events(self):
        """Every grant and revocation in the registry space, push-shaped.

        The registry returns `{rkey, authorDid, record}` — the space metadata
        wrapped around the record, with no `did` and no `event`. Both are
        recoverable without guessing: `event` is which array the entry arrived
        in, and `did` is the leading half of the rkey. Filling them in here is
        what lets the push and the read share one parser, which is the only
        reason there is no second schema to drift from the lexicon.
        """
        if not self.is_configured:
            raise RegistryError(
                "registry is not configured: MEMBERSHIP_REGISTRY_URL and "
                "MEMBERSHIP_REGISTRY_TOKEN must both be set"
            )

        # The token travels as a query parameter, not a POST body, because
        # `syncMembers` has to be an XRPC *query*: HappyView refuses every
        # procedure call with "XRPC procedures require DPoP authentication"
        # before the script ever runs, and a service holding only a shared
        # token cannot produce a DPoP proof. Queries have no such gate.
        #
        # So the token is in the URL, and therefore in access logs. That is why
        # `MEMBERSHIP_REGISTRY_URL` should be the registry's *internal*
        # address: the request never reaches an edge or CDN, and the only log
        # it lands in belongs to a host whose root is already the trust
        # boundary.
        payload = self._query(SYNC_MEMBERS_NSID, {"token": self.token})

        events = []
        for key, event in (("grants", GRANT), ("revocations", REVOKE)):
            entries = payload.get(key)
            if not isinstance(entries, list):
                raise RegistryError(f"registry response has no {key!r} array")
            for entry in entries:
                events.append(self._to_envelope(entry, event))
        return events

    def fetch_applications(self):
        """Everyone who has asked to join, newest first. An `ApplicationList`.

        Reads the index, which is correct **only** for this collection — see
        the "Applications" section above for why that is not a hole in the
        never-read-grants-from-the-index rule.

        Needs the URL, and deliberately not `is_configured`: that also demands
        `MEMBERSHIP_REGISTRY_TOKEN`, which buys nothing here. `listRequests` is
        a query over records that are public in their authors' own repos, so it
        takes no credential at all — verified against production. Tying this
        panel to the reconcile token would hide the queue on a deployment that
        simply has not been given a token it does not need.
        """
        if not self.url:
            raise RegistryError(
                "registry is not configured: MEMBERSHIP_REGISTRY_URL must be set"
            )

        applications, unreadable, cursor, truncated = [], 0, None, False
        for _ in range(APPLICATIONS_MAX_PAGES):
            params = {"limit": APPLICATIONS_PAGE_SIZE}
            if cursor:
                params["cursor"] = cursor
            payload = self._query(LIST_REQUESTS_NSID, params)

            entries = payload.get("requests")
            if not isinstance(entries, list):
                raise RegistryError("registry response has no 'requests' array")

            for entry in entries:
                application = self._to_application(entry)
                if application is None:
                    # Counted, never dropped quietly: a record we cannot read
                    # is a person who asked and would otherwise be invisible.
                    unreadable += 1
                else:
                    applications.append(application)

            cursor = payload.get("cursor")
            if not isinstance(cursor, str) or not cursor:
                break
        else:
            # The loop ran out of pages with a cursor still in hand. Say so
            # rather than presenting a prefix as the whole queue.
            truncated = True

        return ApplicationList(applications, unreadable, truncated)

    @staticmethod
    def _to_application(entry):
        """One indexed `membership.request` row, or None if it cannot be read.

        The index returns the record's fields flat, with the `uri` alongside —
        so the applicant's DID is the repo half of that uri and nothing else.
        A row without a readable uri names nobody, which is the one field with
        no sensible fallback; `createdAt` and `note` each degrade to blank.
        """
        if not isinstance(entry, dict):
            return None
        try:
            did = did_from_uri(entry.get("uri"))
        except PushError:
            return None

        try:
            created_at = _parse_timestamp(entry.get("createdAt"), "createdAt")
        except PushError:
            # A missing or malformed date is not worth losing the applicant
            # over: the console renders an em-dash and the row keeps its place
            # in the order the registry returned it.
            created_at = None

        note = entry.get("note")
        return Application(did, created_at, note if isinstance(note, str) else "")

    @staticmethod
    def _to_envelope(entry, event):
        """One space record, in the shape `parse` already understands.

        A malformed entry is not repaired and not dropped: it is passed through
        with whatever it had, so `reconcile` reports it as unresolved. Silently
        discarding it here would hide a member behind a clean-looking report,
        which is the one failure the whole exercise exists to prevent.
        """
        if not isinstance(entry, dict):
            return {"event": event, "record": {}}

        rkey = entry.get("rkey")
        envelope = {
            "event": event,
            "rkey": rkey,
            "authorDid": entry.get("authorDid"),
            "record": entry.get("record") or {},
        }
        if isinstance(rkey, str):
            try:
                envelope["did"] = did_of(rkey)
            except PushError:
                # Leave `did` absent; `_preview` refuses it and reports the
                # rkey. Better than inventing a subject for a record we cannot
                # read.
                pass
        return envelope

    def reconcile(self, *, dry_run=False):
        """Fetch, resolve, and apply. Returns a `ReconcileReport`.

        The single entry point for every trigger — the console button, the
        management command, and whatever schedules it later — so none of them
        can drift into reconciling differently from the others.

        `fetch_roster` is called directly, not through `is_cluster_admin`,
        precisely because it raises: a roster that could not be fetched would
        otherwise fail closed to "nobody is an admin", and every event would be
        discarded as unauthorised while the report claimed success.
        """
        events = self.fetch_events()
        roster = fetch_roster(refresh=True)
        if not roster.exists:
            # `fetch_roster` answers "absent" rather than raising so that the
            # service account can sign in and write the first one. Here that
            # answer is useless: with no roster every event is unauthorised, so
            # reconciling would empty the cache and report success.
            raise ReconcileError(
                "there is no admin roster record, so no grant can be attributed "
                "to a current admin. Add the first admin before reconciling."
            )
        # Resolves to the module-level function below/above, not this method —
        # the name is shadowed only inside the class body's namespace.
        return reconcile(events, roster, dry_run=dry_run)
